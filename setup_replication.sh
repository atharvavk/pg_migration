#!/usr/bin/env bash
# One-time setup: logical replication db1(5432, primary) -> db2(5433),
# plus a reverse subscription (origin='none') so post-switchover writes
# on db2 replicate back to db1 without loops.
#
# Idempotent: safe to re-run.
#
# Config:
#   PGUSER   the postgres superuser to use everywhere (default: your OS user)
#   REVERSE  1 (default) | 0 — enable/disable the reverse subscription
set -euo pipefail
BASE="$(cd "$(dirname "$0")" && pwd)"
PGUSER="${PGUSER:-$(whoami)}"
PGPORT_A="${PGPORT_A:-5432}"
PGPORT_B="${PGPORT_B:-5433}"
GBPORT="${GBPORT:-6432}"

# --- ensure the two clusters exist (no-op if they already do) ---
"$BASE/bootstrap_clusters.sh"

# --- generate pgbouncer config from template (portable, no hardcoded paths) ---
sed -e "s|@BASE@|$BASE|g" pgbouncer/pgbouncer.ini.template > pgbouncer/pgbouncer.ini
printf '"pgbadmin" ""\n"%s" ""\n' "$PGUSER" > pgbouncer/userlist.txt
# restart pgbouncer if it's running with the previous config
if [ -f pgbouncer/pgbouncer.pid ] && kill -0 "$(cat pgbouncer/pgbouncer.pid 2>/dev/null)" 2>/dev/null; then
  kill "$(cat pgbouncer/pgbouncer.pid)"; sleep 0.5; rm -f pgbouncer/pgbouncer.pid
fi

PG1="psql -h 127.0.0.1 -p $PGPORT_A -d postgres -U $PGUSER -X -v ON_ERROR_STOP=1 -q"
PG2="psql -h 127.0.0.1 -p $PGPORT_B -d postgres -U $PGUSER -X -v ON_ERROR_STOP=1 -q"

echo "== 0. ensure clusters are running (no-op if they already are) =="
for d in db1 db2; do
  if ! pg_ctl -D "$BASE/$d" status >/dev/null 2>&1; then
    pg_ctl -D "$BASE/$d" -l "$BASE/${d}_ctl.log" start >/dev/null 2>&1
  fi
done

echo "== 1. wal_level=logical on both instances (needs restart) =="
$PG1 -c "ALTER SYSTEM SET wal_level = 'logical';" >/dev/null
$PG2 -c "ALTER SYSTEM SET wal_level = 'logical';" >/dev/null

# NOTE: pg_ctl restart fails on a *stopped* server (e.g. right after bootstrap),
# so fall back to start.
pg_ctl -D "$BASE/db1" -l "$BASE/db1_ctl.log" restart >/dev/null 2>&1 \
  || pg_ctl -D "$BASE/db1" -l "$BASE/db1_ctl.log" start >/dev/null 2>&1
pg_ctl -D "$BASE/db2" -l "$BASE/db2_ctl.log" restart >/dev/null 2>&1 \
  || pg_ctl -D "$BASE/db2" -l "$BASE/db2_ctl.log" start >/dev/null 2>&1
sleep 1

for p in $PGPORT_A $PGPORT_B; do
  lvl=$(psql -h 127.0.0.1 -p $p -d postgres -U $PGUSER -Atc 'SHOW wal_level;')
  [ "$lvl" = "logical" ] || { echo "FATAL: wal_level on $p is '$lvl'"; exit 1; }
  echo "   port $p: wal_level=$lvl"
done

echo "== 2. clean slate (idempotent) =="
$PG2 -c "DROP SUBSCRIPTION IF EXISTS sub_names_forward;" >/dev/null
$PG1 -c "DROP SUBSCRIPTION IF EXISTS sub_names_reverse;" >/dev/null
$PG2 -c "DROP PUBLICATION  IF EXISTS pub_names;"        >/dev/null
$PG1 -c "DROP PUBLICATION  IF EXISTS pub_names;"        >/dev/null
$PG2 -c "DROP TABLE IF EXISTS names CASCADE;"           >/dev/null
$PG1 -c "DROP TABLE IF EXISTS names CASCADE;"           >/dev/null

echo "== 3. schema =="
SCHEMA="CREATE TABLE names (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name text NOT NULL,
  last_name  text NOT NULL
);"
$PG1 -c "$SCHEMA"
$PG2 -c "$SCHEMA"

echo "== 4. publication (db1) + subscription (db2) =="
$PG1 -c "CREATE PUBLICATION pub_names FOR TABLE public.names;" >/dev/null
$PG2 -c "CREATE SUBSCRIPTION sub_names_forward
   CONNECTION 'host=127.0.0.1 port=$PGPORT_A dbname=postgres user=$PGUSER'
   PUBLICATION pub_names
   WITH (copy_data = true, origin = 'none');" >/dev/null
$PG2 -c "CREATE PUBLICATION pub_names FOR TABLE public.names;" >/dev/null
if [ "${REVERSE:-1}" = "1" ]; then
  $PG1 -c "CREATE SUBSCRIPTION sub_names_reverse
     CONNECTION 'host=127.0.0.1 port=$PGPORT_B dbname=postgres user=$PGUSER'
     PUBLICATION pub_names
     WITH (copy_data = false, origin = 'none');" >/dev/null
  echo "   reverse replication (db2 -> db1, origin=none) ARMED"
else
  echo "   REVERSE=0 — reverse replication DISABLED; post-switch rows land only on db2"
fi

echo "== 5. wait for initial copy =="
for i in $(seq 1 60); do
  pending=$($PG2 -Atc "SELECT count(*) FROM pg_subscription_rel WHERE srsubstate <> 'r';")
  [ "$pending" = "0" ] && break
  sleep 1
  [ "$i" = "60" ] && { echo "FATAL: initial copy did not complete"; exit 1; }
done

echo "== 6. seed db2 sequence from db1 (sequences are NOT replicated!) =="
read -r LV IC <<<"$( $PG1 -At -F ' ' -c "SELECT last_value, is_called FROM public.names_id_seq;" )"
$PG2 -c "SELECT setval('public.names_id_seq', '$LV'::bigint, '$IC'::boolean);" >/dev/null

echo "== verify =="
c1=$($PG1 -Atc "SELECT count(*) FROM names;")
c2=$($PG2 -Atc "SELECT count(*) FROM names;")
echo "   db1 rows: $c1 | db2 rows: $c2"
[ "$c1" = "$c2" ] || { echo "FATAL: row counts differ"; exit 1; }
echo "SETUP OK — replication db1 -> db2 live, reverse sub armed."
